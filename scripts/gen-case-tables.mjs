// Generates modules/str/case_tables.cpp: the Unicode case mappings `str::to_upper` and
// `str::to_lower` use. The tables are data of the Unicode Character Database, so they are
// generated, not written.
//
//   node scripts/gen-case-tables.mjs [--version 17.0.0] [--ucd <dir>]
//
// The mappings are the unconditional ones:
//   * the simple case mappings of UnicodeData.txt (fields 12 and 13);
//   * the unconditional full mappings of SpecialCasing.txt (a line without a condition), which
//     replace the simple one: 'ß' -> "SS", 'ŉ' -> "ʼN", U+0130 -> "i" and U+0307.
// The conditional ones are left out: the final sigma ('Σ' is always 'σ'), the Lithuanian and
// Turkic rules (a dotless 'ı' is upper-cased to 'I', and 'I' is lower-cased to 'i'), which depend
// on a language or on the context and a string does not know either.
//
// `--ucd` reads UnicodeData.txt and SpecialCasing.txt from a directory instead of downloading
// them from https://www.unicode.org/Public/<version>/ucd/.

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'modules/str/case_tables.cpp')

const args = process.argv.slice(2)
const option = (name, fallback) => {
    const at = args.indexOf(name)
    return at >= 0 ? args[at + 1] : fallback
}
const version = option('--version', '17.0.0')
const dir = option('--ucd', null)

async function source(name) {
    if (dir) {
        const path = join(dir, name)
        if (!existsSync(path)) throw new Error(`${path} does not exist`)
        return readFileSync(path, 'utf8')
    }
    const url = `https://www.unicode.org/Public/${version}/ucd/${name}`
    const response = await fetch(url)
    if (!response.ok) throw new Error(`${url}: ${response.status}`)
    return await response.text()
}

const hex = (text) => text.trim().split(/\s+/).filter(Boolean).map((h) => parseInt(h, 16))

const unicodeData = await source('UnicodeData.txt')
const specialCasing = await source('SpecialCasing.txt')

// code point -> array of code points
const upper = new Map()
const lower = new Map()
for (const line of unicodeData.split('\n')) {
    if (!line) continue
    const f = line.split(';')
    const cp = parseInt(f[0], 16)
    if (f[12]) upper.set(cp, [parseInt(f[12], 16)])
    if (f[13]) lower.set(cp, [parseInt(f[13], 16)])
}
for (const raw of specialCasing.split('\n')) {
    const line = raw.replace(/#.*/, '').trim()
    if (!line) continue
    const f = line.split(';').map((x) => x.trim())
    // code; lower; title; upper; [condition;]
    if (f.length > 5 && f[4] !== '') continue // conditional
    const cp = parseInt(f[0], 16)
    const lo = hex(f[1])
    const up = hex(f[3])
    if (lo.length !== 1 || lo[0] !== cp) lower.set(cp, lo)
    if (up.length !== 1 || up[0] !== cp) upper.set(cp, up)
}

// A table is the entries sorted by code point; a value is the mapped code point, or, with the
// high bit set, a sequence: its length in bits 24..26 and its offset in the pool below.
const pool = []
function table(map) {
    const rows = [...map.entries()].sort((a, b) => a[0] - b[0])
    return rows.map(([cp, to]) => {
        if (to.length === 1) return [cp, to[0]]
        let at = pool.findIndex((_, i) => to.every((v, k) => pool[i + k] === v))
        if (at < 0) {
            at = pool.length
            pool.push(...to)
        }
        return [cp, (0x80000000 | (to.length << 24) | at) >>> 0]
    })
}
const upperRows = table(upper)
const lowerRows = table(lower)

const cell = (n) => '0x' + n.toString(16).toUpperCase()
const lines = (rows) => {
    const chunks = []
    for (let i = 0; i < rows.length; i += 4) {
        chunks.push('    ' + rows.slice(i, i + 4).map(([a, b]) => `{${cell(a)}, ${cell(b)}}`).join(', ') + ',')
    }
    return chunks.join('\n')
}
const poolLines = []
for (let i = 0; i < pool.length; i += 8) {
    poolLines.push('    ' + pool.slice(i, i + 8).map(cell).join(', ') + ',')
}

const text = `// Copyright (c) the OpenCML Organization
// SPDX-License-Identifier: MIT

// GENERATED by scripts/gen-case-tables.mjs from the Unicode Character Database ${version}
// (UnicodeData.txt and SpecialCasing.txt). Do not edit; regenerate with
//
//   node scripts/gen-case-tables.mjs --version ${version}
//
// The unconditional case mappings only: the simple ones, with the unconditional full ones of
// SpecialCasing.txt in place of them. No rule that depends on a language or on the context.

#include "case_tables.h"
#include <iterator>

namespace camel::str {

const char *const kUnicodeVersion = "${version}";

namespace {

constexpr CaseEntry kUpper[] = {
${lines(upperRows)}
};

constexpr CaseEntry kLower[] = {
${lines(lowerRows)}
};

constexpr uint32_t kSequences[] = {
${poolLines.join('\n')}
};

} // namespace

const CaseEntry *upperTable(size_t &count) {
    count = std::size(kUpper);
    return kUpper;
}

const CaseEntry *lowerTable(size_t &count) {
    count = std::size(kLower);
    return kLower;
}

const uint32_t *caseSequences() { return kSequences; }

} // namespace camel::str
`
writeFileSync(out, text)
console.log(`wrote ${out}: ${upperRows.length} upper, ${lowerRows.length} lower, ${pool.length} sequence code points (UCD ${version})`)
