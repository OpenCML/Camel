// Shape-specialized CUDA lowering; all intermediate arrays remain on the device.
#include "tiles/program.h"
#include <algorithm>
#include <sstream>
#include <stdexcept>

namespace camel::tiles {
namespace {
std::string literal(size_t n) { return std::to_string(n) + "ULL"; }
std::string load(size_t id, const std::string &at) {
    return "v[" + std::to_string(id) + "][" + at + "]";
}
std::string broadcastIndex(const Shape &input, const Shape &output) {
    if (input == output)
        return "i";
    if (input.size() > output.size())
        throw std::runtime_error("invalid broadcast rank");
    size_t inStride = 1, outStride = 1;
    std::string expr = "0ULL";
    for (size_t d = output.size(); d-- > 0;) {
        if (d >= output.size() - input.size()) {
            size_t j = d - (output.size() - input.size());
            if (input[j] != 1 && input[j] != output[d])
                throw std::runtime_error("invalid broadcast shape");
            if (input[j] > 1)
                expr += "+((i/" + literal(outStride) + ")%" + literal(input[j]) + ")*" +
                        literal(inStride);
            inStride *= std::max<int64_t>(input[j], 1);
        }
        outStride *= std::max<int64_t>(output[d], 1);
    }
    return expr;
}
} // namespace

void generate(Program &p, bool fuse) {
    schedule(p, fuse);
    std::ostringstream code;
    code << "// Generated by Camel Tiles. f32 buffers; explicit f64 sum accumulation.\n";
    for (auto &launch : p.launches) {
        size_t id     = launch.node;
        const Node &n = p.nodes[id];
        if (n.op == "input")
            continue;
        const size_t count = elements(n.shape);
        code << "// " << n.op << "\nextern \"C\" __global__ void " << launch.name
             << "(float** v) {\n";
        if (n.op == "matmul") {
            const auto &a = p.nodes[n.inputs[0]].shape;
            const auto &b = p.nodes[n.inputs[1]].shape;
            size_t m = a[0], k = a[1], cols = b[1];
            const size_t gx = (cols + 15) / 16, gy = (m + 15) / 16;
            if (gx > 2147483647 || gy > 65535)
                throw std::runtime_error("matrix launch exceeds CUDA grid limits");
            launch.blockX = launch.blockY = 16;
            launch.gridX                  = static_cast<unsigned>(std::max(gx, size_t(1)));
            launch.gridY                  = static_cast<unsigned>(std::max(gy, size_t(1)));
            code << "__shared__ float a[16][16], b[16][16];\n"
                 << "unsigned long long row=(unsigned long long)blockIdx.y*16+threadIdx.y;\n"
                 << "unsigned long long col=(unsigned long long)blockIdx.x*16+threadIdx.x;\n"
                 << "float acc=0.0f;\nfor(unsigned long long base=0; base<" << literal(k)
                 << "; base+=16) {\n"
                 << "a[threadIdx.y][threadIdx.x]=(row<" << literal(m) << " && base+threadIdx.x<"
                 << literal(k) << ")?"
                 << load(n.inputs[0], "row*" + literal(k) + "+base+threadIdx.x") << ":0.0f;\n"
                 << "b[threadIdx.y][threadIdx.x]=(base+threadIdx.y<" << literal(k) << " && col<"
                 << literal(cols) << ")?"
                 << load(n.inputs[1], "(base+threadIdx.y)*" + literal(cols) + "+col") << ":0.0f;\n"
                 << "__syncthreads();\n#pragma unroll\nfor(int t=0;t<16;++t)"
                 << " if(base+t<" << literal(k)
                 << ") acc=fmaf(a[threadIdx.y][t],b[t][threadIdx.x],acc);\n"
                 << "__syncthreads();\n}\nif(row<" << literal(m) << " && col<" << literal(cols)
                 << ") " << load(id, "row*" + literal(cols) + "+col") << "=acc;\n";
        } else {
            launch.gridX = static_cast<unsigned>(std::clamp<size_t>((count + 255) / 256, 1, 65535));
            code << "for(unsigned long long i=(unsigned long "
                    "long)blockIdx.x*blockDim.x+threadIdx.x; i<"
                 << literal(count) << "; i+=(unsigned long long)blockDim.x*gridDim.x) {\n";
            if (launch.members.size() > 1) {
                for (auto member : launch.members)
                    code << "float t" << member << ";\n";
                // Every node retains its f32 rounding point. NVRTC's --fmad=false
                // prevents contraction across these assignments.
                for (auto member : launch.members) {
                    const auto &value = p.nodes[member];
                    auto input        = [&](size_t in) {
                        if (std::find(launch.members.begin(), launch.members.end(), in) !=
                            launch.members.end())
                            return std::string("t") + std::to_string(in);
                        return load(in, broadcastIndex(p.nodes[in].shape, value.shape));
                    };
                    code << "{ float a=" << input(value.inputs[0]) << ";\n";
                    if (value.inputs.size() == 2)
                        code << "float b=" << input(value.inputs[1]) << ";\n";
                    std::string expr;
                    if (value.op == "add")
                        expr = "a+b";
                    if (value.op == "subtract")
                        expr = "a-b";
                    if (value.op == "multiply")
                        expr = "a*b";
                    if (value.op == "divide")
                        expr = "a/b";
                    if (value.op == "maximum")
                        expr = "a<b?b:a";
                    if (value.op == "minimum")
                        expr = "b<a?b:a";
                    if (value.op == "neg")
                        expr = "-a";
                    if (value.op == "abs")
                        expr = "fabsf(a)";
                    if (value.op == "exp")
                        expr = "expf(a)";
                    if (value.op == "log")
                        expr = "logf(a)";
                    if (value.op == "sqrt")
                        expr = "sqrtf(a)";
                    if (value.op == "rsqrt")
                        expr = "1.0f/sqrtf(a)";
                    if (value.op == "relu")
                        expr = "a<0.0f?0.0f:a";
                    code << "t" << member << "=" << expr << "; }\n";
                }
                code << load(id, "i") << "=t" << id << ";\n";
            } else if (n.op == "sum_axis" || n.op == "mean_axis" || n.op == "max_axis") {
                const auto &shape = p.nodes[n.inputs[0]].shape;
                size_t axis = n.attributes[0], width = shape[axis], inner = 1;
                for (size_t d = axis + 1; d < shape.size(); ++d)
                    inner *= shape[d];
                const size_t safeInner = std::max(inner, size_t(1));
                code << "unsigned long long base=(i/" << literal(safeInner) << ")*"
                     << literal(width * inner) << "+i%" << literal(safeInner) << ";\n";
                if (n.op == "max_axis")
                    code << "float acc=" << load(n.inputs[0], "base") << ";\n";
                else
                    code << "double acc=0.0;\n";
                code << "for(unsigned long long r=" << (n.op == "max_axis" ? "1" : "0") << ";r<"
                     << literal(width)
                     << ";++r) { float x=" << load(n.inputs[0], "base+r*" + literal(inner))
                     << ";\n";
                code << (n.op == "max_axis" ? "if(acc<x) acc=x;\n" : "acc+=(double)x;\n");
                code << "}\n" << load(id, "i") << "=(float)(acc";
                if (n.op == "mean_axis")
                    code << "/" << (width ? std::to_string(width) + ".0" : "0.0");
                code << ");\n";
            } else {
                const auto a = load(
                    n.inputs[0],
                    n.op == "reshape" ? "i" : broadcastIndex(p.nodes[n.inputs[0]].shape, n.shape));
                std::string expr;
                if (n.op == "reshape")
                    expr = load(n.inputs[0], "i");
                else if (n.inputs.size() == 2) {
                    auto b = load(n.inputs[1], broadcastIndex(p.nodes[n.inputs[1]].shape, n.shape));
                    if (n.op == "add")
                        expr = "a+b";
                    if (n.op == "subtract")
                        expr = "a-b";
                    if (n.op == "multiply")
                        expr = "a*b";
                    if (n.op == "divide")
                        expr = "a/b";
                    if (n.op == "maximum")
                        expr = "a<b?b:a";
                    if (n.op == "minimum")
                        expr = "b<a?b:a";
                    code << "float a=" << a << ", b=" << b << ";\n";
                } else {
                    code << "float a=" << a << ";\n";
                    if (n.op == "neg")
                        expr = "-a";
                    if (n.op == "abs")
                        expr = "fabsf(a)";
                    if (n.op == "exp")
                        expr = "expf(a)";
                    if (n.op == "log")
                        expr = "logf(a)";
                    if (n.op == "sqrt")
                        expr = "sqrtf(a)";
                    if (n.op == "rsqrt")
                        expr = "1.0f/sqrtf(a)";
                    if (n.op == "relu")
                        expr = "a<0.0f?0.0f:a";
                }
                if (expr.empty())
                    throw std::runtime_error("missing lowering for " + n.op);
                code << load(id, "i") << "=" << expr << ";\n";
            }
            code << "}\n";
        }
        code << "}\n";
    }
    p.source = code.str();
}
} // namespace camel::tiles
