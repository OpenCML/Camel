// Shape-specialized CUDA lowering; all intermediate arrays remain on the device.
#include "tiles/internal/access.h"
#include "tiles/internal/codegen_cache.h"
#include "tiles/internal/index_expr.h"
#include "tiles/internal/kernel_ir.h"
#include "tiles/internal/row_kernel.h"
#include "tiles/internal/scalar_expr.h"
#include "tiles/program.h"
#include <algorithm>
#include <cstdint>
#include <sstream>
#include <stdexcept>

namespace camel::tiles {
void kernel::emitCUDA(Program &p) {
    std::ostringstream code;
    code << "// Generated by Camel Tiles. Typed f32/f64 buffers; ordered sum accumulation.\n";
    code << scalarCudaPreamble();
    for (auto &launch : p.launches) {
        size_t id     = launch.node;
        const Node &n = p.nodes[id];
        if (n.op == "input")
            continue;
        code << "// " << n.op << "\nextern \"C\" __global__ void " << launch.name
             << "(float** v) {\n";
        if (launch.implementation == "row_region") {
            const auto region = rowKernel(p);
            if (!region)
                throw std::runtime_error("invalid row region");
            code << emitBody(rowBody(p, *region, launch));
        } else if (n.op == "loop") {
            code << emitBody(loopBody(p, launch));
        } else if (n.op.starts_with("scalar_")) {
            code << emitBody(scalarBody(p, launch));
        } else if (launch.implementation == "parallel_max") {
            code << emitBody(parallelMaxBody(p, launch));
        } else if (n.op == "matmul") {
            code << emitBody(matmulBody(p, launch));
        } else {
            code << emitBody(serialBody(p, launch));
        }
        code << "}\n";
    }
    p.source = code.str();
}
} // namespace camel::tiles
