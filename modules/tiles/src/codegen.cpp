// Shape-specialized CUDA lowering; all intermediate arrays remain on the device.
#include "tiles/internal/access.h"
#include "tiles/internal/codegen_cache.h"
#include "tiles/internal/index_expr.h"
#include "tiles/internal/kernel_ir.h"
#include "tiles/internal/row_kernel.h"
#include "tiles/internal/scalar_expr.h"
#include "tiles/program.h"
#include <algorithm>
#include <cstdint>
#include <sstream>
#include <stdexcept>

namespace camel::tiles {
void kernel::emitCUDA(Program &p) {
    auto load = [&](size_t id, const std::string &at) {
        if (p.nodes[id].dtype == DType::F64)
            return "reinterpret_cast<double*>(v[" + std::to_string(id) + "])[" + at + "]";
        return "v[" + std::to_string(id) + "][" + at + "]";
    };
    std::ostringstream code;
    code << "// Generated by Camel Tiles. Typed f32/f64 buffers; ordered sum accumulation.\n";
    code << scalarCudaPreamble();
    for (auto &launch : p.launches) {
        if (launch.implementation == "row_region") {
            const auto region = rowKernel(p);
            if (!region)
                throw std::runtime_error("invalid row region");
            code << emitRowKernel(p, *region, launch.name);
            continue;
        }
        size_t id     = launch.node;
        const Node &n = p.nodes[id];
        if (n.op == "input")
            continue;
        code << "// " << n.op << "\nextern \"C\" __global__ void " << launch.name
             << "(float** v) {\n";
        if (n.op.starts_with("scalar_")) {
            launch.blockX = launch.gridX = 1;
            auto operand                 = [&](size_t in) {
                return std::find(launch.members.begin(), launch.members.end(), in) !=
                               launch.members.end()
                           ? "t" + std::to_string(in)
                           : load(in, "0");
            };
            for (auto member : launch.members) {
                const auto &value = p.nodes[member];
                code << "double t" << member << ";\n";
                if (value.op == "constant64") {
                    code << "t" << member << "=__longlong_as_double("
                         << std::to_string(static_cast<uint64_t>(value.attributes[0])) << "ULL);\n";
                    continue;
                }
                code << "{double a=" << operand(value.inputs[0]) << ";\n";
                if (value.inputs.size() == 2)
                    code << "double b=" << operand(value.inputs[1]) << ";\n";
                if (value.op == "scalar_div")
                    code << "if(b==0.0){atomicMin(reinterpret_cast<unsigned*>(v[" << p.nodes.size()
                         << "])," << member << "U);" << load(id, "0") << "=0.0;return;}\n";
                const auto operation = value.op == "scalar_add"   ? "add"
                                       : value.op == "scalar_sub" ? "subtract"
                                       : value.op == "scalar_mul" ? "multiply"
                                       : value.op == "scalar_div" ? "divide"
                                                                  : "neg";
                const auto expr      = elementwiseExpression(operation, DType::F64).cuda();
                code << "t" << member << "=" << expr << ";}\n";
            }
            code << load(id, "0") << "=t" << id << ";\n";
        } else if (launch.implementation == "parallel_max") {
            code << emitBody(parallelMaxBody(p, launch));
        } else if (n.op == "matmul") {
            code << emitBody(matmulBody(p, launch));
        } else {
            code << emitBody(serialBody(p, launch));
        }
        code << "}\n";
    }
    p.source = code.str();
}
} // namespace camel::tiles
