def executorch_counts(root: Path, torch_prefix: str | None) -> None:
    head, date = git_head(root)
    emit("executorch", "executorch", str(root), "git_head", head, "commit", "git rev-parse HEAD of the shallow clone")
    emit("executorch", "executorch", str(root), "git_commit_date", date, "iso8601", "git log -1 --format=%cI")
    train = root / "extension/training"
    exts = CPP_EXTS | PY_EXTS
    rule = "walk extension/training/** *.{cpp,h,py}; lines_total incl comments/blanks; no test dir present"
    tot = ncnb = 0
    subdirs = sorted(p for p in train.iterdir() if p.is_dir())
    for sub in subdirs:
        st = sn = 0
        for f in iter_code_files(sub, exts):
            t, n = count_file(f)
            st += t
            sn += n
        tot += st
        ncnb += sn
        emit("executorch", f"extension/training/{sub.name}", sub.name, "lines_total", st, "lines", rule)
        emit("executorch", f"extension/training/{sub.name}", sub.name, "lines_ncnb", sn, "lines", rule)
    top_files = [f for f in train.iterdir() if f.is_file() and f.suffix in exts]
    ft = fn = 0
    for f in sorted(top_files):
        t, n = count_file(f)
        ft += t
        fn += n
    tot += ft
    ncnb += fn
    emit("executorch", "extension/training TOTAL", "extension/training/", "lines_total", tot, "lines", rule)
    emit("executorch", "extension/training TOTAL", "extension/training/", "lines_ncnb", ncnb, "lines", rule)
    grad_pat = re.compile(r"register.*(gradient|grad)|IMPLEMENT.*GRADIENT|GradientBuilder", re.I)
    hits = 0
    for f in iter_code_files(train, exts):
        for line in f.read_text(encoding="utf-8", errors="ignore").splitlines():
            if grad_pat.search(line):
                hits += 1
    emit(
        "executorch",
        "per_op_gradient_registrations",
        "extension/training/",
        "registrations",
        hits,
        "entries",
        'grep -riE "register.*(gradient|grad)|IMPLEMENT.*GRADIENT|GradientBuilder" extension/training/ | wc -l (script-verified absence if 0)',
    )
    if torch_prefix:
        exp = Path(torch_prefix) / "torch/export/experimental/__init__.py"
        if exp.is_file():
            t, n = count_file(exp)
            emit(
                "executorch",
                "torch_export_experimental",
                "torch/export/experimental/__init__.py (pytorch/pytorch, host torch install)",
                "lines_total",
                t,
                "lines",
                "home of _export_forward_backward; lives in pytorch/pytorch, not executorch",
            )
            for i, line in enumerate(exp.read_text(encoding="utf-8", errors="ignore").splitlines(), 1):
                if "_export_forward_backward" in line and line.strip().startswith("def "):
                    emit(
                        "executorch",
                        "_export_forward_backward",
                        "torch/export/experimental/__init__.py",
                        "def_line",
                        i,
                        "line_no",
                        "definition site of the forward/backward export helper",
                    )
        else:
            emit("executorch", "torch_export_experimental", torch_prefix, "lines_total", "FILE_NOT_FOUND", "lines", "torch prefix lookup failed")


# ---------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--mode", required=True, choices=["camel", "relax", "ort", "executorch"])
    ap.add_argument("--repo", default=".", help="Camel repo root (camel/relax modes)")
    ap.add_argument("--root", default=".", help="clone root (ort/executorch modes)")
    ap.add_argument("--torch-prefix", default=None, help="site-packages prefix containing torch/ (executorch mode)")
    args = ap.parse_args()

    print(HEADER)
    if args.mode == "camel":
        repo = Path(args.repo).resolve()
        head, date = git_head(repo)
        emit("camel", "camel", str(repo), "git_head", head, "commit", "git rev-parse HEAD of the measured working tree")
        emit("camel", "camel", str(repo), "git_commit_date", date, "iso8601", "git log -1 --format=%cI")
        camel_lines(repo)
        camel_setvjp(repo)
        camel_onnx_map(repo)
    elif args.mode == "relax":
        relax_counts(Path(args.repo).resolve())
    elif args.mode == "ort":
        ort_counts(Path(args.root).resolve())
    elif args.mode == "executorch":
        executorch_counts(Path(args.root).resolve(), args.torch_prefix)
    return 0


if __name__ == "__main__":
    sys.exit(main())
