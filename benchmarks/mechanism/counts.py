r"""T10 mechanism counts -- counting engine. Runs locally (Camel repo) and on the
server (onnxruntime / executorch clones). Python 3.10+, stdlib only.

Every number is emitted to stdout as one CSV row:

    section,item,scope,metric,value,unit,rule

so the archived counts.csv / details.csv can be regenerated byte-identically by
re-running this script. Nothing is filled in by hand.

Counting calibrations (see NOTES.md):
  * lines_total : number of physical lines (str.splitlines), comments and blank
                  lines included; test files are excluded only where stated.
  * lines_ncnb  : non-comment non-blank lines. C/C++: // and block comments
                  stripped with a string-literal-aware state machine (handles
                  "..."/'...'/R"(...)"); blank lines dropped. Python: tokenize
                  based; lines touched only by COMMENT/NL tokens dropped;
                  docstrings are statements and count as code.
  * setVjp      : literal registrations setVjp(defs, "name", fn) count 1 each;
                  a registration loop `for (std::string_view name : {..names..})
                  { setVjp(defs, name, fn); }` counts len(names). The setVjp
                  definition/declaration (vjp.cpp/vjp.h) is not matched by the
                  call regex. kind=rule vs kind=zero_grad_stub is decided by
                  whether the rule argument contains "noGradient".
  * onnx_map    : literal entries match the same regex as
                  scripts/gen_export_matrix.py:
                      add\(\s*"([^"]+)"\s*,\s*(.+?)\s*(?:,\s*(\d+)\s*)?\)\s*;
                  dynamic entries are add(...) calls whose first argument is not
                  a string literal; each counts N = product of the cardinalities
                  of the enclosing `for (.. : {"a","b",..})` loops (brace
                  tracking on the comment/string-stripped line structure).
  * grad_reg    : per-operator gradient registrations in a foreign codebase,
                  counted by a stated grep/regex pattern so absence (0) is as
                  reproducible as presence.
"""

