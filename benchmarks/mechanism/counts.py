CPP_EXTS = {".c", ".cc", ".cpp", ".cxx", ".h", ".hh", ".hpp", ".cu", ".cuh"}
PY_EXTS = {".py"}

HEADER = "section,item,scope,metric,value,unit,rule"


# ---------------------------------------------------------------- line counter

def _strip_c_line(line: str, in_block: bool, blank_strings: bool) -> tuple[str, bool]:
    """Strip comments from one C/C++ line. Returns (remaining_code, in_block).
    String/char literals are replaced by a single 'x' (blank_strings=True) so
    braces inside strings cannot confuse scope tracking; when blank_strings is
    False the literal content is kept (needed for registration-name regexes)."""
    out: list[str] = []
    i, n = 0, len(line)
    while i < n:
        if in_block:
            j = line.find("*/", i)
            if j == -1:
                return "".join(out), True
            in_block = False
            i = j + 2
            continue
        c = line[i]
        if c == "/" and i + 1 < n and line[i + 1] == "/":
            break
        if c == "/" and i + 1 < n and line[i + 1] == "*":
            in_block = True
            i += 2
            continue
        if c == "R" and i + 1 < n and line[i + 1] == '"':
            j = line.find(')"', i + 2)
            out.append("x" if blank_strings else line[i : (j + 2 if j != -1 else n)])
            i = (j + 2) if j != -1 else n
            continue
        if c in "\"'":
            j = i + 1
            while j < n:
                if line[j] == "\\":
                    j += 2
                    continue
                if line[j] == c:
                    j += 1
                    break
                j += 1
            out.append("x" if blank_strings else line[i:j])
            i = j
            continue
        out.append(c)
        i += 1
    return "".join(out), in_block


def c_ncnb(text: str) -> int:
    in_block = False
    count = 0
    for line in text.splitlines():
        code, in_block = _strip_c_line(line, in_block, blank_strings=True)
        if code.strip():
            count += 1
    return count


def py_ncnb(text: str) -> int:
    code_lines: set[int] = set()
    skip = {
        tokenize.COMMENT,
        tokenize.NL,
        tokenize.NEWLINE,
        tokenize.INDENT,
        tokenize.DEDENT,
        tokenize.ENCODING,
        tokenize.ENDMARKER,
    }
    try:
        toks = tokenize.generate_tokens(io.StringIO(text).readline)
        for tok in toks:
            if tok.type in skip:
                continue
            for ln in range(tok.start[0], tok.end[0] + 1):
                code_lines.add(ln)
    except (tokenize.TokenError, IndentationError, SyntaxError):
        return sum(1 for ln in text.splitlines() if ln.strip() and not ln.lstrip().startswith("#"))
    return len(code_lines)


def count_file(path: Path) -> tuple[int, int]:
    text = path.read_text(encoding="utf-8", errors="ignore")
    total = len(text.splitlines())
    if path.suffix in PY_EXTS:
        return total, py_ncnb(text)
    return total, c_ncnb(text)


def iter_code_files(root: Path, exts: set[str]) -> list[Path]:
    return sorted(p for p in root.rglob("*") if p.is_file() and p.suffix in exts)


# ---------------------------------------------------------------- csv emit

ROWS: list[tuple[str, str, str, str, object, str, str]] = []
WRITER = csv.writer(sys.stdout, lineterminator="\n")


def emit(section: str, item: str, scope: str, metric: str, value: object, unit: str, rule: str) -> None:
    row = (section, item, scope, metric, value, unit, rule)
    ROWS.append(row)
    WRITER.writerow(row)


def git_head(root: Path) -> tuple[str, str]:
    def _git(*args: str) -> str:
        return subprocess.check_output(["git", "-C", str(root), *args], text=True).strip()

    try:
        return _git("rev-parse", "HEAD"), _git("log", "-1", "--format=%cI")
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "unknown", "unknown"


# ---------------------------------------------------------------- camel mode

SETVJP_CALL = re.compile(r'setVjp\(\s*defs\s*,\s*"([^"]+)"\s*,\s*([^;]+?)\)\s*;')
SETVJP_VAR = re.compile(r"setVjp\(\s*defs\s*,\s*name\s*,")
FOR_NAMES = re.compile(r"for\s*\(.*:\s*\{([^}]*)\}")


def camel_setvjp(repo: Path) -> None:
    rule_desc = (
        'regex setVjp\\(defs,"name",fn) =1 per literal; loop for(name:{..}){setVjp(defs,name,fn)} '
        "counts len(names); definition site vjp.cpp/vjp.h not matched; kind=zero_grad_stub iff rule arg contains noGradient"
    )
    per_module: dict[str, dict[str, int]] = {}
    scanned_roots = ["modules", "src", "include", "test"]
    for root_name in scanned_roots:
        root = repo / root_name
        if not root.is_dir():
            continue
        for cpp in iter_code_files(root, CPP_EXTS):
            text = cpp.read_text(encoding="utf-8", errors="ignore")
            lines = text.splitlines()
            rel = cpp.relative_to(repo).as_posix()
            relparts = cpp.relative_to(root).parts
            if root_name == "modules" and len(relparts) > 1:
                module = relparts[0]
            else:
                module = root_name
            bucket = per_module.setdefault(module, {"rule": 0, "zero_grad_stub": 0, "call_sites": 0})
            for m in SETVJP_CALL.finditer(text):
                kind = "zero_grad_stub" if "noGradient" in m.group(2) else "rule"
                bucket[kind] += 1
                bucket["call_sites"] += 1
            for i, line in enumerate(lines):
                if not SETVJP_VAR.search(line):
                    continue
                bucket["call_sites"] += 1
                names: list[str] = []
                for j in range(i, max(-1, i - 6), -1):
                    fm = FOR_NAMES.search(lines[j])
                    if fm:
                        names = re.findall(r'"([^"]+)"', fm.group(1))
                        break
                kind = "zero_grad_stub" if "noGradient" in line else "rule"
                bucket[kind] += len(names)
                emit(
                    "camel_setvjp",
                    "loop_expansion",
                    f"{rel}:{i + 1}",
                    "registrations",
                    len(names),
                    "entries",
                    "loop over {" + ",".join(names) + "}",
                )
    for module in sorted(per_module):
        b = per_module[module]
        total = b["rule"] + b["zero_grad_stub"]
        if total == 0:
            continue
        emit("camel_setvjp", f"module:{module}", f"{module}/", "registrations", total, "entries", rule_desc)
        emit("camel_setvjp", f"module:{module}", f"{module}/", "of_which_rules", b["rule"], "entries", rule_desc)
        emit(
            "camel_setvjp",
            f"module:{module}",
            f"{module}/",
            "of_which_zero_grad_stubs",
            b["zero_grad_stub"],
            "entries",
            rule_desc,
        )
    grand = sum(b["rule"] + b["zero_grad_stub"] for b in per_module.values())
    rules = sum(b["rule"] for b in per_module.values())
    emit("camel_setvjp", "TOTAL", "modules+src+include+test", "registrations", grand, "entries", rule_desc)
    emit("camel_setvjp", "TOTAL", "modules+src+include+test", "of_which_rules", rules, "entries", rule_desc)
    emit(
        "camel_setvjp",
        "TOTAL",
        "modules+src+include+test",
        "of_which_zero_grad_stubs",
        grand - rules,
        "entries",
        rule_desc,
    )


ADD_LITERAL = re.compile(r'(?<![\w.])add\(\s*"([^"]+)"\s*,\s*(.+?)\s*(?:,\s*(\d+)\s*)?\)\s*;')
ADD_ANY = re.compile(r"(?<![\w.])add\s*\(")
FOR_LIST = re.compile(r"for\s*\(.*:\s*\{([^}]*)\}")


def count_registry(path: Path, section: str, scope: str) -> tuple[int, int]:
    text = path.read_text(encoding="utf-8", errors="ignore")
    literal = dynamic = 0
    in_block_keep = False
    in_block_struct = False
    depth = 0
    stack: list[tuple[int, int]] = []
    for lineno, raw in enumerate(text.splitlines(), 1):
        keep, in_block_keep = _strip_c_line(raw, in_block_keep, blank_strings=False)
        struct, in_block_struct = _strip_c_line(raw, in_block_struct, blank_strings=True)
        mult = 1
        for d, m in stack:
            if d <= depth:
                mult *= m
        fm = FOR_LIST.search(struct)
        opens = struct.count("{")
        closes = struct.count("}")
        if fm:
            card = len(re.findall(r'"([^"]*)"', keep))
            if opens > 0:
                stack.append((depth + 1, card))
        for m in ADD_LITERAL.finditer(keep):
            literal += mult
        dyn_hits = len(ADD_ANY.findall(keep)) - len(ADD_LITERAL.findall(keep))
        if dyn_hits > 0:
            dynamic += dyn_hits * mult
            emit(
                section,
                "dynamic_site",
                f"{path.name}:{lineno}",
                "registrations",
                dyn_hits * mult,
                "entries",
                f"add() with non-literal first arg inside loop cardinalities product={mult}: {keep.strip()[:80]}",
            )
        depth += opens - closes
        stack = [(d, m) for d, m in stack if d <= depth]
    emit(
        section,
        path.name,
        scope,
        "registrations_literal",
        literal,
        "entries",
        'literal add("uri",fn[,opset]); same regex as scripts/gen_export_matrix.py',
    )
    emit(
        section,
        path.name,
        scope,
        "registrations_dynamic",
        dynamic,
        "entries",
        "add() with non-literal first arg, expanded by enclosing for(..:{..}) loop cardinalities",
    )
    emit(
        section,
        path.name,
        scope,
        "registrations_total",
        literal + dynamic,
        "entries",
        "literal + dynamic (runtime registry size)",
    )
    return literal, dynamic


def camel_onnx_map(repo: Path) -> None:
    lit_f, dyn_f = count_registry(repo / "modules/onnx/lowering.cpp", "camel_onnx_map", "modules/onnx")
    lit_g, dyn_g = count_registry(repo / "modules/onnx/lowering_grad.cpp", "camel_onnx_map", "modules/onnx")
    emit(
        "camel_onnx_map",
        "forward",
        "modules/onnx/lowering.cpp",
        "registrations_total",
        lit_f + dyn_f,
        "entries",
        "forward lowering registry size at runtime",
    )
    emit(
        "camel_onnx_map",
        "gradient",
        "modules/onnx/lowering_grad.cpp",
        "registrations_total",
        lit_g + dyn_g,
        "entries",
        "gradient lowering registry size at runtime (addGradientLowerings)",
    )
    matrix = repo / "export_matrix.csv"
    if matrix.is_file():
        fwd = grad = 0
        rows = matrix.read_text(encoding="utf-8").splitlines()[1:]
        for row in rows:
            parts = row.split(",")
            if len(parts) >= 3:
                if parts[1]:
                    fwd += 1
                if parts[2]:
                    grad += 1
        emit(
            "camel_onnx_map",
            "export_matrix.csv",
            "repo root snapshot",
            "forward_rows_with_lowering",
            fwd,
            "entries",
            "committed snapshot generated by scripts/gen_export_matrix.py (may lag HEAD)",
        )
        emit(
            "camel_onnx_map",
            "export_matrix.csv",
            "repo root snapshot",
            "gradient_rows_with_lowering",
            grad,
            "entries",
            "committed snapshot generated by scripts/gen_export_matrix.py (may lag HEAD)",
        )
        cur_lit = {m.group(1) for m in ADD_LITERAL.finditer((repo / "modules/onnx/lowering.cpp").read_text(encoding="utf-8"))}
        cur_grad = {
            m.group(1) for m in ADD_LITERAL.finditer((repo / "modules/onnx/lowering_grad.cpp").read_text(encoding="utf-8"))
        }
        snap_f = {r.split(",")[0] for r in rows if len(r.split(",")) >= 3 and r.split(",")[1]}
        snap_g = {r.split(",")[0] for r in rows if len(r.split(",")) >= 3 and r.split(",")[2]}
        emit(
            "camel_onnx_map",
            "matrix_delta_forward",
            "HEAD vs snapshot",
            "uris_added_since_snapshot",
            ";".join(sorted(cur_lit - snap_f)) or "none",
            "uris",
            "literal registry URIs at HEAD minus snapshot rows (explains any count delta)",
        )
        emit(
            "camel_onnx_map",
            "matrix_delta_gradient",
            "HEAD vs snapshot",
            "uris_added_since_snapshot",
            ";".join(sorted(cur_grad - snap_g)) or "none",
            "uris",
            "literal registry URIs at HEAD minus snapshot rows (explains any count delta)",
        )


def camel_lines(repo: Path) -> None:
    rule = "lines_total=splitlines incl comments/blanks; lines_ncnb=comment/blank-stripped; *.cpp/*.h only; no test files under these dirs"
    groups = {
        "camel_onnx": repo / "modules/onnx",
        "camel_autodiff": repo / "modules/autodiff",
    }
    for section, root in groups.items():
        tot = ncnb = 0
        for f in iter_code_files(root, CPP_EXTS):
            t, n = count_file(f)
            tot += t
            ncnb += n
            emit(section, f.name, f.relative_to(repo).as_posix(), "lines_total", t, "lines", rule)
            emit(section, f.name, f.relative_to(repo).as_posix(), "lines_ncnb", n, "lines", rule)
        emit(section, "TOTAL", root.relative_to(repo).as_posix(), "lines_total", tot, "lines", rule)
        emit(section, "TOTAL", root.relative_to(repo).as_posix(), "lines_ncnb", ncnb, "lines", rule)
    opt_root = repo / "src/passes/opt"
    tot = ncnb = 0
    for sub in sorted(p for p in opt_root.iterdir() if p.is_dir()):
        st = sn = 0
        for f in iter_code_files(sub, CPP_EXTS):
            t, n = count_file(f)
            st += t
            sn += n
        tot += st
        ncnb += sn
        emit("camel_opt_passes", sub.name, f"src/passes/opt/{sub.name}", "lines_total", st, "lines", rule)
        emit("camel_opt_passes", sub.name, f"src/passes/opt/{sub.name}", "lines_ncnb", sn, "lines", rule)
    emit("camel_opt_passes", "TOTAL", "src/passes/opt", "lines_total", tot, "lines", rule)
    emit("camel_opt_passes", "TOTAL", "src/passes/opt", "lines_ncnb", ncnb, "lines", rule)


def relax_counts(repo: Path) -> None:
    path = repo / "benchmarks/e12tvm/onnx2relax.py"
    text = path.read_text(encoding="utf-8")
    total = len(text.splitlines())
