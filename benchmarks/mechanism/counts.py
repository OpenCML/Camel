def ort_counts(root: Path) -> None:
    head, date = git_head(root)
    emit("ort", "onnxruntime", str(root), "git_head", head, "commit", "git rev-parse HEAD of the shallow clone")
    emit("ort", "onnxruntime", str(root), "git_commit_date", date, "iso8601", "git log -1 --format=%cI")
    gb_files = sorted((root / "orttraining/orttraining/core/graph").glob("gradient_builder*"))
    macro_hist: dict[str, int] = {}
    macro_re = re.compile(r"^\s*([A-Z][A-Z0-9_]*(?:GRADIENT|gradient)[A-Z0-9_]*)\s*\(", re.M)
    impl_re = re.compile(r"IMPLEMENT_GRADIENT_BUILDER\s*\(\s*(Get\w+)")
    registry_re = re.compile(r'REGISTER_GRADIENT_BUILDER\(\s*"')
    total_impl = total_registry = 0
    for f in gb_files:
        text = f.read_text(encoding="utf-8", errors="ignore")
        for name in macro_re.findall(text):
            macro_hist[name] = macro_hist.get(name, 0) + 1
        impls = impl_re.findall(text)
        regs = registry_re.findall(text)
        total_impl += len(impls)
        total_registry += len(regs)
        t, n = count_file(f)
        emit(
            "ort",
            f.name,
            "orttraining/orttraining/core/graph",
            "lines_total",
            t,
            "lines",
            "splitlines incl comments/blanks",
        )
        emit(
            "ort",
            f.name,
            "orttraining/orttraining/core/graph",
            "gradient_builder_registrations",
            len(impls),
            "entries",
            "IMPLEMENT_GRADIENT_BUILDER(GetXxxGradient) macro invocations",
        )
        emit(
            "ort",
            f.name,
            "orttraining/orttraining/core/graph",
            "registry_entries",
            len(regs),
            "entries",
            'REGISTER_GRADIENT_BUILDER("Op", GetXxxGradient) static registration-table entries',
        )
    emit(
        "ort",
        "per_op_gradient_registrations",
        "orttraining/orttraining/core/graph",
        "registrations",
        total_registry,
        "entries",
        "GradientBuilderRegistry static table size = REGISTER_GRADIENT_BUILDER entries across gradient_builder*",
    )
    emit(
        "ort",
        "per_op_gradient_registrations",
        "orttraining/orttraining/core/graph",
        "of_which_implemented_via_implement_macro",
        total_impl,
        "entries",
        "builders implemented via IMPLEMENT_GRADIENT_BUILDER in gradient_builder.cc",
    )
    for name, cnt in sorted(macro_hist.items()):
        emit(
            "ort",
            "macro_histogram",
            "orttraining/orttraining/core/graph/gradient_builder*",
            f"macro:{name}",
            cnt,
            "invocations",
            "all-caps macro invocations whose name contains GRADIENT (context for the registration count)",
        )
    train_root = root / "orttraining"
    rule = "walk orttraining/** ; lines_total incl comments/blanks; per extension class; test dirs INCLUDED unless excluded explicitly"
    for exts, label in [(CPP_EXTS, "cpp"), (PY_EXTS, "py")]:
        tot = ncnb = 0
        for f in iter_code_files(train_root, exts):
            t, n = count_file(f)
            tot += t
            ncnb += n
        emit("ort", f"orttraining_tree_{label}", "orttraining/", "lines_total", tot, "lines", rule)
        emit("ort", f"orttraining_tree_{label}", "orttraining/", "lines_ncnb", ncnb, "lines", rule)
    core_graph = root / "orttraining/orttraining/core/graph"
    tot = ncnb = 0
    for f in iter_code_files(core_graph, CPP_EXTS):
        t, n = count_file(f)
        tot += t
        ncnb += n
    emit(
        "ort",
        "core_graph_cpp",
        "orttraining/orttraining/core/graph/",
        "lines_total",
        tot,
        "lines",
        "gradient/training-graph machinery subset of the training tree",
    )
    emit(
        "ort",
        "core_graph_cpp",
        "orttraining/orttraining/core/graph/",
        "lines_ncnb",
        ncnb,
        "lines",
        "gradient/training-graph machinery subset of the training tree",
    )


