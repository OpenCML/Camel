"""Does a header's interface alone suffice for the translation units that name it?

Two shapes of the interface are tried, and both are generated by the same rewriter:

  decls    aliases + enums + function declarations + forward declarations of every class and struct
  records  the same, but the POD record structs keep their layout

Each shape is written to its own directory as `<header>`, that directory is placed first on the `-I`
path so it wins over the real header, and every translation unit of the compile-commands database
that names the header is compiled with `-fsyntax-only`.  A TU counts as "the interface suffices"
only when both gates pass: it compiles, *and* none of its diagnostics land inside the generated
header.  A rewrite can be perfectly self-consistent and still say something other than what the
header said, so one gate without the other is not a reading.

Run it from the repository root of the tree whose build wrote the database:

    python3 internal/tools/header-weight-iface.py

Every path it touches is a parameter; `--help` names each one and the default it takes.
"""
import argparse
import collections
import json
import os
import re
import shlex
import socket
import subprocess
import sys
import tempfile
import time
from concurrent.futures import ThreadPoolExecutor

PROG = 'header-weight-iface.py'
ANSI = re.compile(r'\x1b\[[0-9;]*m')

EPILOG = """\
Traps this tool is shaped around.  Each is marked in the source at the line that avoids it:

  braces      brace counting skips comments and string literals.  This header's comments carry
              both '{' and '}', so counting a raw line ends a block in the wrong place and the
              stub silently keeps or drops whole definitions.
  namespace   whether a declaration owns a body is decided by which of ';' and '{' comes first on
              the same scan, never by "is there a '{' later": every declaration is followed
              eventually by some brace -- the next function's, the enclosing namespace's -- and a
              look-ahead with no ';' bound rewrites the declaration as a body and deletes
              everything up to that brace.
  incomplete  once a type is a forward declaration, a namespace-scope instance of it and an
              inline constexpr variable of it cannot compile any more, because the type is
              incomplete right there.  Those lines are dropped along with the definition that
              owned them, so an incompleteness this rewrite created is not charged to a TU.
  both gates  the stub must compile *and* no error may land inside it.  A self-consistent rewrite
              is not the same claim as one that still says what the header said, and a stub that
              is broken fails every TU for a reason that is not about those TUs.

Exit codes: 0 a reading was produced -- the counts are the answer, including a count of TUs that
need more than the interface; 2 the tool could not measure anything, and says what was missing.
"""


def die(message):
    sys.stderr.write('%s: %s\n' % (PROG, message))
    raise SystemExit(2)


def code_only(line):
    """`line` with string literals removed and a `//` comment cut off.

    Trap: a brace inside a comment or a string literal is not a brace of the program.  This
    header's comments sketch shapes and name initializers, so they carry both `{` and `}`, and
    counting the raw line ends a definition in the wrong place: the stub then keeps the tail of a
    body, or drops the declarations that came after it.
    """
    out, i, in_str = [], 0, False
    while i < len(line):
        ch = line[i]
        if in_str:
            if ch == '\\':
                i += 2
                continue
            if ch == '"':
                in_str = False
            i += 1
            continue
        if ch == '"':
            in_str = True
            i += 1
            continue
        if ch == '/' and i + 1 < len(line) and line[i + 1] == '/':
            break
        out.append(ch)
        i += 1
    return ''.join(out)


def bc(line):
    """Net brace count of one line of code, comments and literals excluded."""
    c = code_only(line)
    return c.count('{') - c.count('}')


def strip(header_path, keep_records):
    """The declarations-only rewrite of one header.

    `keep_records` keeps the bodies of record `struct`s (the `records` shape); every other
    definition loses its body and becomes a declaration.
    """
    lines = open(header_path, encoding='utf-8').read().splitlines()
    out, i, skip = [], 0, None
    while i < len(lines):
        line = lines[i]
        if skip is not None:
            # Inside a definition whose body is being dropped: count down to its closing brace.
            skip += bc(line)
            if skip <= 0:
                skip = None
            i += 1
            continue
        s = line.strip()
        if not s or s.startswith('//'):
            out.append(line)
            i += 1
            continue
        if s.startswith('static_assert') or (s.startswith('inline constexpr') and 'sizeof(' in s):
            # Trap: a forward declaration makes the type incomplete at this point of the file, so a
            # namespace-scope instance of it, and an `inline constexpr` variable of it, stop
            # compiling the moment its definition is rewritten.  Both are dropped with the
            # definition that owned them: charging that break to a TU would report "this TU needs
            # more than the interface" about a TU that needs nothing.
            i += 1
            continue
        m = re.match(r'^(class|struct)\s+(\w+)\b', s)
        if m and '{' in s and not s.rstrip().endswith(';'):
            if not (m.group(1) == 'struct' and keep_records):
                out.append('%s %s;' % (m.group(1), m.group(2)))
                sk = bc(line)
                skip = sk if sk > 0 else 1
                i += 1
                continue
        if s.startswith('enum') and '{' in s:
            # An enum definition is already a declaration, and its enumerators are the named
            # constants the rest of the interface is written in: dropping the body would delete
            # names, not bodies.
            depth = bc(line)
            out.append(line)
            i += 1
            while depth > 0 and i < len(lines):
                out.append(lines[i])
                depth += bc(lines[i])
                i += 1
            continue
        if s.startswith('template'):
            # A template definition cannot be reduced to a declaration that still instantiates, so
            # it is dropped whole rather than half-rewritten.
            depth, started = 0, False
            while i < len(lines):
                depth += bc(lines[i])
                if '{' in code_only(lines[i]):
                    started = True
                i += 1
                if started and depth <= 0:
                    break
            continue
        if '(' in code_only(s) and not s.startswith('namespace'):
            j, buf, term = i, [], None
            while j < len(lines):
                buf.append(lines[j])
                c = code_only(lines[j])
                ib, isemi = c.find('{'), c.find(';')
                if ib != -1 or isemi != -1:
                    # Trap: decide by which of ';' and '{' comes first, not by whether a '{'
                    # appears somewhere ahead.  Every declaration is followed eventually by some
                    # brace -- the next function's body, the enclosing namespace's -- and a
                    # look-ahead with no ';' bound treats a declaration as a definition, deleting
                    # every line up to that brace, the `namespace ... {` line included.
                    term = '{' if (ib != -1 and (isemi == -1 or ib < isemi)) else ';'
                    break
                j += 1
            if term == ';':
                # A declaration already: copy it verbatim, however many lines it spans.
                out.extend(buf)
                i = j + 1
                continue
            if term == '{':
                head = '\n'.join(buf)
                cb = code_only(head)
                head = head[:cb.rindex('{')].rstrip()
                out.append(head + ';')
                depth = bc(lines[j])
                depth = depth if depth > 0 else 1
                i = j + 1
                while depth > 0 and i < len(lines):
                    depth += bc(lines[i])
                    i += 1
                continue
        out.append(line)
        i += 1
    return '\n'.join(out) + '\n'


def strip_args(cmd):
    """The compiler invocation with everything that writes a file removed, and `-O*` dropped.

    What is compiled does not change: `-c`, `-o`, `-MF` and friends only decide what is written,
    and an optimisation level cannot change whether a line of C++ is valid.  The caller appends
    `-fsyntax-only`.
    """
    a = shlex.split(cmd)
    rest, i = [], 1
    while i < len(a):
        if a[i] in ('-o', '-MF', '-MT', '-MQ', '-MJ'):
            i += 2
            continue
        if a[i] in ('-c', '-M', '-E', '-S', '-MD', '-MMD'):
            i += 1
            continue
        rest.append(a[i])
        i += 1
    return [a[0]] + [x for x in rest if not x.startswith('-O')]


def load_db(db_path):
    """`{source: entry}` with the first entry per source, plus the entry count.

    A source appears once per build configuration in the database; the first entry is the one this
    tool compiles, which is the same rule the reading this replaces used.
    """
    try:
        with open(db_path, encoding='utf-8') as f:
            db = json.load(f)
    except (OSError, ValueError) as exc:
        die('cannot read the compile-commands database at %s: %s' % (db_path, exc))
    if not db:
        die('the compile-commands database at %s is empty: it names no translation unit, so there '
            'is nothing to compile' % db_path)
    if 'command' not in db[0]:
        die('the database entry for %s has no `command` field; this tool reads the `command` form '
            'only' % db[0].get('file', '<unknown>'))
    by_src = {}
    for e in db:
        by_src.setdefault(e['file'], e)
    return by_src, db


def warn_if_foreign(entry, db_path):
    """Say so when the database was written by a build whose tree this process cannot see.

    The database's `directory` fields are absolute paths from the machine that ran the build.  When
    they do not resolve here, the flags point at a tree that is not the one under this process, and
    every count below would describe that other tree.
    """
    directory = entry.get('directory', '')
    if directory and not os.path.isdir(directory):
        sys.stderr.write(
            '%s: warning: the database at %s names a build directory this machine cannot see '
            '(%s); it was written by a build elsewhere, or the tree moved.  The reading below '
            'describes the tree those paths name, not the one this process can see.\n'
            % (PROG, db_path, directory))


def naming_tus(by_src, header_name):
    """The TUs whose source writes an include of `header_name` itself."""
    inc = re.compile(r'^\s*#\s*include\s*[<"]([^>"]+)[>"]')
    naming = []
    for src in by_src:
        try:
            for line in open(src, encoding='utf-8', errors='replace'):
                mm = inc.match(line)
                if mm and mm.group(1) == header_name:
                    naming.append(src)
                    break
        except OSError:
            # A source the database names but this machine cannot read is not a TU that names the
            # header; it is a TU nobody can say anything about.
            pass
    return naming


def parse_args(argv):
    def_overlay = os.path.join(tempfile.gettempdir(), 'camel-header-weight', 'iface')
    p = argparse.ArgumentParser(
        prog=PROG,
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=EPILOG,
    )
    p.add_argument('--root', default=os.getcwd(),
                   help='the tree the database belongs to, and the tree the header is read from. '
                        'Default: the current directory, so the tool is meant to be run from the '
                        'repository root.')
    p.add_argument('--db', default=None,
                   help='the compile-commands database: it names the translation units and their '
                        'compile flags. Default: <root>/build/compile_commands.json, which is '
                        'where the build writes it.')
    p.add_argument('--include-root', default='src/kernel/include',
                   help='the directory the header is named from -- the one on the `-I` path. '
                        'Default: %(default)s.')
    p.add_argument('--header', default='camel/runtime/graph.h',
                   help='the header to reduce, relative to --include-root; the same relative name '
                        'is used for the generated stub, so it wins over the real one on `-I`. '
                        'Default: %(default)s.')
    p.add_argument('--overlay-dir', default=def_overlay,
                   help='where the generated stubs are written, one subdirectory per shape, each '
                        'holding the header at its include name. Default: %(default)s (a scratch '
                        'path under the system temp directory).')
    p.add_argument('--out-dir', default=None,
                   help='where the per-shape JSON readings are written. Default: --overlay-dir.')
    p.add_argument('--jobs', type=int, default=8,
                   help='how many translation units are compiled at once. Default: %(default)s.')
    p.add_argument('--host', default=socket.gethostname(),
                   help='the machine this reading describes; recorded in the output header line '
                        'and in the JSON so a number can be quoted with its source. Default: this '
                        "machine's hostname. It moves no work: the commands run here, so the "
                        'database must have been written by a build on this machine, or its '
                        'absolute `directory` paths must resolve here.')
    opts = p.parse_args(argv)
    if opts.jobs < 1:
        p.error('--jobs must be at least 1')
    return opts


def run_mode(mode, keep_records, opts, by_src, db_path, naming):
    incdir = os.path.join(opts.overlay_dir, mode)
    os.makedirs(os.path.join(incdir, os.path.dirname(opts.header)), exist_ok=True)
    stub = os.path.join(incdir, opts.header)
    with open(stub, 'w', encoding='utf-8') as f:
        f.write(strip(opts.header_path, keep_records))
    real_lines = len(open(opts.header_path, encoding='utf-8').read().splitlines())
    stub_lines = len(open(stub, encoding='utf-8').read().splitlines())
    print('=== mode %s: stub %d lines (real %d)' % (mode, stub_lines, real_lines))

    def compile_tu(src):
        e = by_src[src]
        c = strip_args(e['command'])
        # The overlay goes before every other `-I` so the stub is the header that is opened.
        c = c[:1] + ['-I', incdir] + c[1:] + ['-fsyntax-only']
        r = subprocess.run(c, cwd=e['directory'], stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        err = ANSI.sub('', r.stderr.decode(errors='replace'))
        # Trap: both gates are required.  "The stub compiles" alone cannot tell a faithful
        # declaration from one that dropped something the TUs needed; "no error inside the stub"
        # alone cannot tell a stub that works from one that says nothing.  A diagnostic located
        # inside the stub is charged to the stub and the TU becomes unjudgeable, never a TU that
        # needs more than the interface -- a self-consistent rewrite is not the same claim as one
        # that still says what the header said.
        in_stub = [l for l in err.splitlines()
                   if ': error:' in l and l.split(':')[0].startswith(incdir)]
        other = [l for l in err.splitlines()
                 if ': error:' in l and not l.split(':')[0].startswith(incdir)]
        return r.returncode == 0, in_stub, other

    started = time.time()
    with ThreadPoolExecutor(max_workers=opts.jobs) as ex:
        res = list(ex.map(compile_tu, naming))
    elapsed = time.time() - started
    ok = [s for s, (good, a, b) in zip(naming, res) if good]
    broken = [s for s, (good, a, b) in zip(naming, res) if not good and a]
    genuine = [(s, b) for s, (good, a, b) in zip(naming, res) if not good and not a]
    print('    TUs naming %s: %d   compile with this interface: %d'
          % (opts.header, len(naming), len(ok)))
    print('    unjudgeable (error inside the stub): %d' % len(broken))
    print('    need more than the interface: %d' % len(genuine))
    c = collections.Counter()
    for s, errs in genuine:
        msg = ' / '.join(sorted({e.split(': error:')[-1].strip()[:58] for e in errs})[:1])
        loc = os.path.relpath(errs[0].split(':')[0], opts.root) if errs else '?'
        c[(msg, loc.split('/')[-1])] += 1
    for (msg, loc), n in c.most_common(10):
        print('       %3d  [%s] %s' % (n, loc, msg))
    for s in ok:
        print('    OK:', os.path.relpath(s, opts.root))
    json.dump({'host': opts.host, 'root': opts.root, 'db': db_path, 'jobs': opts.jobs,
               'header': opts.header, 'mode': mode, 'keep_records': keep_records,
               'elapsed_s': round(elapsed, 1),
               'ok': [os.path.relpath(s, opts.root) for s in ok],
               'broken': [os.path.relpath(s, opts.root) for s in broken],
               'genuine': [[os.path.relpath(s, opts.root), e[:2]] for s, e in genuine]},
              open(os.path.join(opts.out_dir, '%s.json' % mode), 'w', encoding='utf-8'), indent=1)


def main(argv=None):
    opts = parse_args(argv)
    opts.root = os.path.abspath(opts.root)
    opts.header_path = os.path.normpath(os.path.join(opts.root, opts.include_root, opts.header))
    db_path = opts.db or os.path.join(opts.root, 'build', 'compile_commands.json')
    opts.db = db_path
    opts.out_dir = opts.out_dir or opts.overlay_dir
    opts.overlay_dir = os.path.abspath(opts.overlay_dir)
    opts.out_dir = os.path.abspath(opts.out_dir)

    if not os.path.isfile(opts.header_path):
        die('no header at %s: run from the repository root, or name the tree with --root (and the '
            'header with --include-root/--header)' % opts.header_path)
    if not os.path.isfile(db_path):
        die('no compile-commands database at %s: the database names the translation units and '
            'their flags, so nothing can be compiled without it. Build the tree first, or name '
            'the database with --db' % db_path)
    by_src, db = load_db(db_path)
    warn_if_foreign(db[0], db_path)
    naming = naming_tus(by_src, opts.header)
    if not naming:
        die('no translation unit in %s includes %s: either the database was written by a tree '
            'that does not name it, or --header/--include-root is wrong' % (db_path, opts.header))

    os.makedirs(opts.overlay_dir, exist_ok=True)
    os.makedirs(opts.out_dir, exist_ok=True)
    print('=== host=%s root=%s db=%s jobs=%d' % (opts.host, opts.root, db_path, opts.jobs))
    run_mode('decls', False, opts, by_src, db_path, naming)
    print()
    run_mode('records', True, opts, by_src, db_path, naming)
    return 0


if __name__ == '__main__':
    sys.exit(main())