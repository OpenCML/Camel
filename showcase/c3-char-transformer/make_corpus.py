"""Write the corpus C3 trains on, and nothing else.

The corpus is committed (`corpus.txt`), a few kilobytes, and this script is the record of how it
was made: 96 lines drawn from eight sentence templates by a small linear congruential generator
with a fixed seed, so the file can be regenerated byte for byte and a reader does not have to trust
a text of unknown provenance.

Why a synthetic corpus and not a book: the example is about the *gradient*, not the text.  A model
that can be trained on a laptop needs a text with learnable structure and no licensing question,
and the eight templates give the model something to learn -- the same six words appear in the same
places, so a character model that has learned anything predicts "the " after a period better than
chance.  The alphabet is the 28 characters `' abcdefghijklmnopqrstuvwxyz.'`; anything outside it
(a capital, a digit) would be folded to the space by `class_of` in train.cml.

    python showcase/c3-char-transformer/make_corpus.py
    python showcase/c3-char-transformer/make_corpus.py --out corpus.txt --lines 96 --seed 11
"""

import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent

# The words the templates draw from: all lowercase, all inside the alphabet.
SUBJECTS = ["the model", "the gradient", "the compiler", "the graph", "the library", "the runner"]
VERBS = ["reads", "writes", "keeps", "moves", "folds", "checks"]
OBJECTS = ["a tensor", "the rule", "a window", "the loss", "a cotangent", "the mask"]
PLACES = ["in the graph", "on the node", "at the edge", "under the rule", "beside the split"]

TEMPLATES = [
    "{s} {v} {o} {p}.",
    "{s} {v} {o}.",
    "when {s} {v} {o} the pass runs.",
    "{s} {v} {o} and {v} {o}.",
    "if {s} {v} {o} it is kept.",
    "{s} {v} {o} {p} and stops.",
    "the rule says {s} {v} {o}.",
    "{s} {v} {o} so the next step is cheap.",
]


def draw(state, modulo):
    """The next value of the generator: a 32-bit linear congruential step, kept small on purpose."""
    state = (state * 1103515245 + 12345) & 0x7FFFFFFF
    return state, state % modulo


def build(lines, seed):
    state = seed
    out = []
    for _ in range(lines):
        state, template = draw(state, len(TEMPLATES))
        state, subject = draw(state, len(SUBJECTS))
        state, verb = draw(state, len(VERBS))
        state, obj = draw(state, len(OBJECTS))
        state, place = draw(state, len(PLACES))
        out.append(
            TEMPLATES[template].format(
                s=SUBJECTS[subject], v=VERBS[verb], o=OBJECTS[obj], p=PLACES[place]
            )
        )
    return "".join(line + "\n" for line in out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(HERE / "corpus.txt"))
    parser.add_argument("--lines", type=int, default=96)
    parser.add_argument("--seed", type=int, default=11)
    args = parser.parse_args()
    text = build(args.lines, args.seed)
    Path(args.out).write_text(text, encoding="utf-8")
    used = sorted(set(text))
    print(f"corpus path={args.out} lines={args.lines} bytes={len(text.encode('utf-8'))} "
          f"characters={len(text)} alphabet={len(used)}")
    print(f"corpus characters={' '.join(repr(c) for c in used)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())