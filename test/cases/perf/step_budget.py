def shape_rates_from_probe(text: str) -> dict:
    """The probe's per-shape rows: the `shape=` line, then its phase line and its `compare` line,
    which is where the same product's OpenBLAS rate at the same thread count is printed."""
    out = {}
    current = None
    for line in text.splitlines():
        match = re.match(r"shape=(\S+) threads=(\d+) cpu_ms=([0-9.]+) wall_ms=([0-9.]+) "
                         r"gflops=([0-9.]+)", line)
        if match:
            current = {"cpu_ms": float(match.group(3)), "gflops": float(match.group(5)),
                       "threads": int(match.group(2))}
            out[match.group(1)] = current
            continue
        compare = re.search(r"compare naive_gflops=([0-9.]+) blas_gflops=([0-9.]+) "
                            r"vs_blas=([0-9.]+)", line)
        if compare and current is not None:
            current["blas_gflops"] = float(compare.group(2))
            current["vs_blas"] = float(compare.group(3))
    if not out:
        raise SystemExit("the probe printed no shape rows")
    return out


