"""Where one d=256 Camel training step's time goes, and the two guards that keep the answer stable.

The step is the showcase program `examples/models/naive-in-expert-out/train_step.cml` at the
extents the sweep's d=256 cell uses (batch 16 x sequence 32, d_model 256, 16 heads of width 16,
FFN 512, vocabulary 32, two blocks).  The file is generated by substituting exactly those extents,
as `measure.py` does; the program's own `naive config` line is checked against the cell before a
number is accepted.

Modes

  count    The guard.  One profiled run of the step, three rounds, and the operator call counts of
           a round must equal CALLS_PER_STEP below.  A change that doubles a product, adds a pass
           over the parameters or reorders the graph so backward stops running fails here, on a
           count rather than on a duration: no timing is asserted.

  elementwise
           The guard for the element-wise kernels: every element-wise operator of the step
           allocates exactly one allocator block per call, the output.  A kernel that materializes
           an intermediate allocates more; a count of blocks, not a duration.

  budget   The perf case.  Measures the step's CPU time (two run lengths, so the start-up
           cancels), profiles the step and its two phases (forward; forward + backward; full), and
           prints the budget with every row measured and the residual named.  The invariants are
           structural: every row present and positive, the rows accounting for the round mean
           within a stated band, the counts the ones `count` pins, and the forward/backward split
           accounting for all of the element-wise time.

  measure  The same plus the canonical GEMM's per-shape CPU time from test/tools/gemmprobe (which
           needs the build host's compiler) and the per-operator element-wise probe (one operator at
           one of the step's own shapes, the run repeated -- the repeats are the null control),
           written as one JSON document.  This is the file committed under the example's results/.

Why the absolute numbers are normalised.  `std::profile` times operators with `steady_clock`, and
the reference host is shared: a step that costs 62 ms of CPU time measured 126-138 ms of wall time
during this work, with the load average around 120 on 32 hardware threads.  The step's CPU time is
measured from the slope of a run's CPU seconds against its step count, which preemption does not
change; each row's *share* is measured inside one run, where every row is inflated by the same
host; the row's milliseconds are its share of the round mean times the measured CPU step.  The one
independent check that this normalisation is honest is the matmul row: the GEMM probe measures the
same products in CPU time on the same core, and the two numbers agree to a few percent (§ the
report).  See docs/technical/54_profiler_allocations.md for the instrument.

Usage
  python step_budget.py count
  python step_budget.py budget
  python step_budget.py measure --json examples/models/naive-in-expert-out/results/<date>-d256-step-budget.json
"""

