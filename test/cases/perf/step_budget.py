# ---------------------------------------------------------------------------
# Generating the step


def generate(cell: dict, steps: int, warmup: int = 3, phase: str = "full",
             prints: bool = True) -> str:
    """train_step.cml at this cell, with the phase's timed body and optionally its prints."""
    text = TRAIN_STEP.read_text(encoding="utf-8")
    for old, new, count in SUBSTITUTIONS:
        got = text.count(old)
        if got != count:
            raise SystemExit(f"train_step.cml changed shape: {old!r} occurs {got} times, "
                             f"expected {count}")
        text = text.replace(old, new.format(steps=steps, **cell))
    # The initial and final loss are printed once each, outside the step.  Removing them keeps the
    # profile's rows to the loop's own calls, so a row divided by the round count is a per-step
    # number rather than a per-step plus two evaluations.
    for name in ("before", "after"):
        old = f"    let {name} = loss<{'model' if name == 'before' else 'trained'}>(x, labels)"
        if text.count(old) != 1:
            raise SystemExit(f"train_step.cml changed shape: {old!r} not found once")
        text = text.replace(old, f"    let {name} = 0.0")
    if not prints:
        for line in ('            if bench && i >= warmup then {\n'
                     '                `naive bench step=${i} ms=${elapsed * 1000.0:.6f}`->println\n'
                     '            }\n',
                     '            `naive step=${i} loss=${value:.9f}`->println\n'):
            if text.count(line) != 1:
                raise SystemExit(f"train_step.cml changed shape: {line!r} not found once")
            text = text.replace(line, "")
    if phase == "forward":
        # No gradient and no update: the same forward graph, called once per round.
        old = ("            let (value, gradient) = loss_grad<m>(x, labels)\n"
               "            let next = adam(m, gradient, st, lr)")
        if text.count(old) != 1:
            raise SystemExit("train_step.cml changed: the timed body is not the expected one")
        text = text.replace(old, "            let value = loss<m>(x, labels)\n"
                                 "            let next = (m, st)")
    elif phase == "forward-backward":
        old = "            let next = adam(m, gradient, st, lr)"
        if text.count(old) != 1:
            raise SystemExit("train_step.cml changed: the update is not the expected one")
        text = text.replace(old, "            let next = (m, st)")
    return text


def expected_products(cell: dict) -> dict:
    """The products one round issues, derived from the program's own shapes.

    For C = A @ B with A[m, k] and B[k, n], the gradient along the left argument is
    dC[m, n] @ B^T[n, k] (m x k x n, B transposed) and along the right one is
    A^T[k, m] @ dC[m, n] (k x n x m, A transposed).
    """
    tokens, d = cell["batch"] * cell["sequence"], cell["d_model"]
    d_ff, vocab, blocks = cell["d_ff"], cell["vocab"], cell["blocks"]

    def left(m, k, n):
        return f"{m}x{k}x{n}tB"

    def right(m, k, n):
        return f"{k}x{n}x{m}tA"

    forward = {
        f"{tokens}x{d}x{d}": 4 * blocks,          # q, k, v, wo
        f"{tokens}x{d_ff}x{d}": blocks,           # w1
        f"{tokens}x{d}x{d_ff}": blocks,           # w2
        f"{tokens}x{vocab}x{d}": 1,               # the vocabulary projection
    }
    out = dict(forward)
    for m, k, n in ((tokens, d, d), (tokens, d, d_ff), (tokens, d_ff, d), (tokens, d, vocab)):
        count = forward[f"{m}x{n}x{k}"]
        out[left(m, k, n)] = count
        out[right(m, k, n)] = count
    return out


# ---------------------------------------------------------------------------
# Running the program


def camel_exe() -> str:
    override = os.environ.get("CAMEL_EXE")
    if override:
        return override
    tag = "debug" if os.environ.get("CAMEL_TIER") == "debug" else "latest"
    return str(REPO / "out" / tag / "bin" / ("camel.exe" if os.name == "nt" else "camel"))


def environment() -> dict:
    env = dict(os.environ)
    env.setdefault("CAMEL_HOME", str(REPO / "out" / "latest"))
    return env


def run(program: Path, passes: list[str], args: list[str] | None = None,
        cpu_time: bool = False) -> dict:
    command = [camel_exe(), "-t", "1", "--block-limit", "8192", str(program), *passes]
    command += args if args is not None else ["--arg", "bench=false", "--arg", "init_dir=",
                                              "--arg", "final_dir="]
    if cpu_time:
        command = ["/usr/bin/time", "-f", "cpu %U %S"] + command
    started = time.perf_counter()
    proc = subprocess.run(command, env=environment(), capture_output=True, text=True)
    wall = time.perf_counter() - started
    cpu = None
    match = re.search(r"^cpu ([0-9.]+) ([0-9.]+)$", proc.stderr, re.MULTILINE)
    if match:
        cpu = float(match.group(1)) + float(match.group(2))
    if proc.returncode != 0:
        raise SystemExit(f"camel failed ({proc.returncode}):\n{proc.stdout[-2000:]}\n"
                         f"{proc.stderr[-2000:]}")
    return {"command": command, "cpu": cpu, "wall": wall, "stdout": proc.stdout,
            "stderr": proc.stderr}


def bench_ms(stdout: str) -> list[float]:
    return [float(m.group(1)) for m in re.finditer(r"naive bench step=\d+ ms=([0-9.]+)", stdout)]


def median(values: list[float]):
    return sorted(values)[len(values) // 2] if values else None


def profile(program: Path, backend: str = "std::jit") -> dict:
    """Run the program under `std::profile`; the session must be armed before the scheduler."""
    with tempfile.TemporaryDirectory() as t:
        report = Path(t) / "profile.json"
        result = run(program, ["tensor::fuse", "std::profile", "report=true",
                               f'json="{report.as_posix()}"', "top=0", backend],
                     ["--arg", "bench=true", "--arg", "init_dir=", "--arg", "final_dir="])
        if not report.exists():
            raise SystemExit(f"std::profile wrote no JSON report:\n{result['stdout'][-2000:]}")
        doc = json.loads(report.read_text(encoding="utf-8"))
        doc["_bench"] = bench_ms(result["stdout"])
        doc["_stdout"] = result["stdout"]
        return doc


def config_line(stdout: str) -> dict:
    match = re.search(r"naive config batch=(\d+) sequence=(\d+) d_model=(\d+) heads=(\d+) "
                      r"d_ff=(\d+) vocab=(\d+) blocks=(\d+) params=(\d+)", stdout)
    if not match:
        raise SystemExit("the program printed no config line")
    keys = ("batch", "sequence", "d_model", "heads", "d_ff", "vocab", "blocks", "params")
    return {key: int(match.group(i + 1)) for i, key in enumerate(keys)}


def load_average() -> float:
    try:
        return float(Path("/proc/loadavg").read_text().split()[0])
    except OSError:
        return float("nan")


def per_step(doc: dict) -> dict[str, dict]:
    """Operator ns per round, for the operators that run every round.

    A row whose calls are not a multiple of the round count ran partly or wholly outside the loop
    (the weights' `randn`, the optimizer's state, `with_grad`); those are start-up, not the step.
    """
    rounds = doc["step"]["rounds"]
    out = {}
    for row in doc["operator_rows"]:
        if row["calls"] and row["calls"] % rounds == 0:
            out[row["uri"]] = {"ns": row["ns"] / rounds, "calls": row["calls"] / rounds}
    return out


def row_alloc_per_step(doc: dict) -> dict[str, float]:
    rounds = doc["step"]["rounds"]
    return {row["uri"]: row["alloc_ns"] / rounds for row in doc["operator_rows"]}


