def shape_rates_from_probe(text: str) -> dict:
    """The probe's per-shape rows: the `shape=` line, then its phase line and its `compare` line,
    which is where the same product's OpenBLAS rate at the same thread count is printed."""
    out = {}
    current = None
    for line in text.splitlines():
        match = re.match(r"shape=(\S+) threads=(\d+) cpu_ms=([0-9.]+) wall_ms=([0-9.]+) "
                         r"gflops=([0-9.]+)", line)
        if match:
            current = {"cpu_ms": float(match.group(3)), "gflops": float(match.group(5)),
                       "threads": int(match.group(2))}
            out[match.group(1)] = current
            continue
        compare = re.search(r"compare naive_gflops=([0-9.]+) blas_gflops=([0-9.]+) "
                            r"vs_blas=([0-9.]+)", line)
        if compare and current is not None:
            current["blas_gflops"] = float(compare.group(2))
            current["vs_blas"] = float(compare.group(3))
    if not out:
        raise SystemExit("the probe printed no shape rows")
    return out


ELEMENTWISE_PROGRAM = """module elementwise_rate

import {{ Tensor, seed, set_num_threads, sum, zeros }} from tensor
import {{ now }} from time

// The same call Camel's step makes: two dense f32 tensors of one shape, one operator, one output.
// The clock is inside the process and brackets the loop only, so the start-up is not in the number
// and the same protocol can be used on the torch side.
func main(reps: int): int sync {{
    set_num_threads(1)
    seed(7)
    let x = zeros([{rows}, {cols}]) + 0.5
    let y = zeros([{rows}, {cols}]) + 1.5
    let warm = loop i = 0 while i < 32 do {{
        let product = x {op} y
        return i + 1
    }}
    let start = now()
    let (i_last, last) = loop i = 0, t = x while i < reps do {{
        return (i + 1, x {op} y)
    }}
    let elapsed = now() - start
    let check = sum(last)
    `elementwise op={opname} reps=${{reps}} ms=${{elapsed * 1000.0:.6f}} check=${{check}}`->println
    return 0
}}
"""

TORCH_PROGRAM = """import sys
import time
import torch

torch.set_num_threads(1)
op, rows, cols, reps = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4])
x = torch.full((rows, cols), 0.5)
y = torch.full((rows, cols), 1.5)
for _ in range(32):
    p = x * y if op == "multiply" else x / y
start = time.perf_counter()
for _ in range(reps):
    p = x * y if op == "multiply" else x / y
print(f"elementwise op={op} reps={reps} ms={(time.perf_counter() - start) * 1000.0:.6f}")
"""


def timed_loop_ms(command: list[str], pattern: str, cwd: Path) -> float:
    proc = subprocess.run(command, cwd=str(cwd), capture_output=True, text=True,
                          env=environment())
    if proc.returncode != 0:
        raise SystemExit(f"{command[0]} failed ({proc.returncode}):\n"
                         f"{proc.stdout[-1000:]}\n{proc.stderr[-1000:]}")
    match = re.search(pattern, proc.stdout)
    if not match:
        raise SystemExit(f"no timing line from {command[0]}:\n{proc.stdout[-1000:]}")
    return float(match.group(1))


def elementwise_side_by_side(reps: int = 2000) -> dict:
    """One operator, one shape, one thread, the same protocol on both sides: the only element-wise
    comparison that is the same call in both frameworks.  Three runs each, the least preempted one
    kept (this host's load moves by a factor of two inside a minute)."""
    python = os.environ.get("CAMEL_TORCH_PYTHON")
    if not python:
        candidate = Path.home() / "camel-eval/venv-bench/bin/python"
        python = str(candidate) if candidate.exists() else sys.executable
    work = Path(tempfile.mkdtemp(prefix="elementwise-"))
    (work / "torch_rate.py").write_text(TORCH_PROGRAM, encoding="utf-8")
    pin = ["taskset", "-c", os.environ.get("CAMEL_PROBE_CPU", "30")] if os.name != "nt" else []
    out = {}
    for op, sign, rows, cols in (("multiply", "*", 512, 512), ("divide", "/", 512, 256)):
        program = work / f"{op}.cml"
        program.write_text(ELEMENTWISE_PROGRAM.format(rows=rows, cols=cols, op=sign, opname=op),
                           encoding="utf-8")
        commands = {
            "camel": [camel_exe(), "-t", "1", str(program), "std::jit", "--arg", f"reps={reps}"],
            "torch": [python, str(work / "torch_rate.py"), op, str(rows), str(cols), str(reps)],
        }
        entry = {"shape": f"{rows}x{cols}", "elements": rows * cols, "reps": reps}
        for name, command in commands.items():
            samples = [timed_loop_ms(pin + command, r"\bms=([0-9.]+)", work) for _ in range(5)]
            ms = min(samples)
            ns_per_call = ms * 1e6 / reps
            elements = rows * cols
            # One read of each operand and one write of the output.
            gbs = 3 * elements * 4 / (ns_per_call * 1e-9) / 1e9
            entry[name] = {"ns_per_call": ns_per_call, "gbs": gbs, "samples_ms": samples}
        entry["camel_over_torch"] = entry["camel"]["ns_per_call"] / entry["torch"]["ns_per_call"]
        out[op] = entry
    return out


def run_probe() -> dict:
    script = REPO / "test/tools/gemmprobe"
    proc = subprocess.run(["sh", str(script / "run.sh"), "--threads", "1", "--reps", "7"],
                          cwd=str(REPO), capture_output=True, text=True, env=environment())
    if proc.returncode != 0:
        raise SystemExit(f"the GEMM probe failed:\n{proc.stdout[-2000:]}\n{proc.stderr[-2000:]}")
    header = [line for line in proc.stdout.splitlines() if line.startswith(("clock ", "machine "))]
    return {"command": "sh test/tools/gemmprobe/run.sh --threads 1 --reps 7",
            "shapes": shape_rates_from_probe(proc.stdout), "header": header}


def budget(with_probe: bool, with_torch: bool, steps: int, warmup: int) -> dict:
    steps = max(steps, 32)
    work = Path(tempfile.mkdtemp(prefix="step-budget-"))
    result = {"schema": 1, "cell": CELL, "steps": steps, "warmup": warmup,
              "load_average": {"before": load_average()}, "generated": {}}
    programs = {}
    for phase, prints in [("full", True), ("full", False), ("forward-backward", False),
                          ("forward", False)]:
        name = phase + ("" if prints else "-quiet")
        source = generate(CELL, steps, warmup, phase=phase, prints=prints)
        programs[name] = work / f"{name}.cml"
        programs[name].write_text(source, encoding="utf-8")
        result["generated"][name] = {"phase": phase, "prints": prints,
                                     "sha256": hashlib.sha256(source.encode()).hexdigest()}
    tiny_source = generate(TINY, steps, warmup, prints=False)
    programs["tiny"] = work / "tiny.cml"
    programs["tiny"].write_text(tiny_source, encoding="utf-8")
    result["generated"]["tiny"] = {"phase": "full", "prints": False,
                                   "sha256": hashlib.sha256(tiny_source.encode()).hexdigest()}

    # The step's CPU time: the start-up is common to both lengths and cancels in the difference.
    # The two lengths are 96 steps apart because the start-up's own system time moves by a few
    # tenths of a second from process to process on this host, and a 24-step separation multiplied
    # that by 1/24.
    short = 32
    long = max(steps, 128)
    short_program = work / "short.cml"
    short_program.write_text(generate(CELL, short, warmup), encoding="utf-8")
    long_program = work / "long.cml"
    long_program.write_text(generate(CELL, long, warmup), encoding="utf-8")
    timed = {}
    for name, program, n in [("short", short_program, short), ("long", long_program, long)]:
        samples = []
        for _ in range(3):
            measured = run(program, ["tensor::fuse", "std::jit"], cpu_time=True,
                           args=["--arg", "bench=true", "--arg", "init_dir=",
                                 "--arg", "final_dir="])
            samples.append({
                "cpu_seconds": measured["cpu"] if measured["cpu"] is not None else measured["wall"],
                "median_ms": median(bench_ms(measured["stdout"]))})
        # The median, not the minimum: the start-up of the process (about 0.2-0.4 s, and its
        # system time moves with the host's memory pressure) is what the two lengths cancel, and a
        # minimum over samples picks the luckiest start rather than the typical one.
        best = sorted(samples, key=lambda sample: sample["cpu_seconds"])[len(samples) // 2]
        timed[name] = dict(best, steps=n, cpu_samples=[s["cpu_seconds"] for s in samples])
    cpu_step = (timed["long"]["cpu_seconds"] - timed["short"]["cpu_seconds"]) / (long - short) \
        * 1000.0
    result["timed"] = timed
    result["step_cpu_ms"] = cpu_step
    result["step_wall_median_ms"] = timed["long"]["median_ms"]

    expected_config = {"batch": 16, "sequence": 32, "d_model": 256, "heads": 16, "d_ff": 512,
                       "vocab": 32, "blocks": 2, "params": 1059584}
    profiles = {}
    for name in ("full-quiet", "forward-backward-quiet", "forward-quiet", "tiny"):
        doc = profile(programs[name])
        config = config_line(doc["_stdout"])
        want = dict(expected_config, batch=1, sequence=1) if name == "tiny" else expected_config
        if config != want:
            raise SystemExit(f"the {name} program ran {config}, not {want}")
        profiles[name] = doc
        rows = per_step(doc)
        result.setdefault("profile", {})[name] = {
            "rounds": doc["step"]["rounds"],
            "round_mean_ms": doc["step"]["wall_per_round_ns"] / 1e6,
            "row_sum_ms": sum(r["ns"] for r in rows.values()) / 1e6,
            "bench_median_ms": median(doc["_bench"]),
            "operator_calls": doc["operators"]["calls"],
            "untimed_calls": doc["operators"]["untimed"],
            "overhead_ns": doc["operators"]["overhead_ns"],
            "allocator_ns_per_step": doc["step"]["allocations_per_round"]["ns"],
            "allocator_blocks_per_step": doc["step"]["allocations_per_round"]["blocks"],
        }

    full = profiles["full-quiet"]
    round_mean = full["step"]["wall_per_round_ns"] / 1e6
    rows = per_step(full)
    forward_rows = per_step(profiles["forward-quiet"])
    both_rows = per_step(profiles["forward-backward-quiet"])
    forward_round = profiles["forward-quiet"]["step"]["wall_per_round_ns"] / 1e6
    both_round = profiles["forward-backward-quiet"]["step"]["wall_per_round_ns"] / 1e6
    tiny_round = profiles["tiny"]["step"]["wall_per_round_ns"] / 1e6
    tiny_rows = per_step(profiles["tiny"])
    allocation = row_alloc_per_step(full)

    def ms(ns_per_step: float) -> float:
        """A row's share of the round, carried onto the step's measured CPU time."""
        return ns_per_step / 1e6 / round_mean * cpu_step

    def share_of(ns_per_step: float) -> float:
        return ns_per_step / 1e6 / round_mean

    def forward_fraction(uri: str) -> float:
        """The forward part of a row: its calls in the forward-only build over its calls in the
        step.  A count, not a duration: the backward half of an operator chain calls some operators
        more often than the forward half, and the count says by how much."""
        total = rows.get(uri, {}).get("calls", 0.0)
        if total <= 0:
            return 1.0
        return min(1.0, forward_rows.get(uri, {}).get("calls", 0.0) / total)

    table = []

    def add(row: str, ns_per_step: float, detail: str = "") -> None:
        if ns_per_step <= 0:
            return
        table.append({"row": row, "ms": ms(ns_per_step), "share": share_of(ns_per_step),
                      "detail": detail})

    add("allocation (the allocator calls inside every row below)",
        sum(allocation.values()),
        f"{full['step']['allocations_per_round']['blocks']:.1f} block payloads per step")

    if with_probe:
        probe = run_probe()
        result["probe"] = probe
        products = {}
        projections = 0.0
        for shape, count in PRODUCT_COUNTS.items():
            if shape not in probe["shapes"]:
                raise SystemExit(f"the probe did not measure {shape}")
            entry = probe["shapes"][shape]
            products[shape] = dict(entry, calls=count)
            projections += count * entry["cpu_ms"]
        attention = 0.0
        micro = 0
        for shape, sides in ATTENTION.items():
            if shape not in probe["shapes"]:
                raise SystemExit(f"the probe did not measure {shape}")
            per = probe["shapes"][shape]["cpu_ms"]
            for side in ("forward", "backward"):
                attention += sides[side] * per
                micro += sides[side]
            products[shape] = {"cpu_ms": per, "gflops": probe["shapes"][shape]["gflops"],
                               "micro_calls": sides}
        result["products"] = products
        # These two come from the probe, in CPU time on the same core and the same thread count as
        # the step: they are absolute and are not carried by the profile's share (the residual is
        # the two instruments' disagreement).
        table.append({"row": "matmul, projections (per shape, probe CPU time)",
                      "ms": projections, "share": projections / cpu_step,
                      "detail": f"{sum(PRODUCT_COUNTS.values())} calls per step"})
        table.append({"row": "matmul, attention products (per call at 32x32x16)",
                      "ms": attention, "share": attention / cpu_step,
                      "detail": f"{micro} micro products per step, 4 batched calls forward and 8 "
                                "backward"})
        result["matmul_measured_ms"] = projections + attention
    else:
        projections = None
        add("matmul (the three profiled rows)", sum(rows[uri]["ns"] for uri in MATMUL_URIS if uri in rows))

    # The forward/backward split: a ratio of two measured shares, so the two runs' different load
    # inflations cancel.
    for uri in sorted(rows, key=lambda name: -ms(rows[name]["ns"])):
        if uri in MATMUL_URIS:
            continue
        net = rows[uri]["ns"] - allocation.get(uri, 0.0)
        if net <= 0:
            continue
        if uri in ELEMENTWISE:
            fwd = forward_fraction(uri)
            add(f"elementwise, forward: {uri}", net * fwd)
            add(f"elementwise, backward: {uri}", net * (1 - fwd))
        elif uri in REDUCE:
            add(f"reduction: {uri}", net)
        elif uri in LAYOUT:
            add(f"layout: {uri}", net)
        elif uri == "nn:adam":
            add("optimizer: nn:adam", net)
        else:
            add(f"other: {uri}", net)

    between_ns = max(0.0, tiny_round - sum(r["ns"] for r in tiny_rows.values()) / 1e6) * 1e6
    add("framework: between operator calls (measured at 1x1 tokens)", between_ns,
        f"{full['step']['operators_per_round']:.1f} operator calls per step")

    total = sum(row["ms"] for row in table)
    result["rows_ns_per_step"] = {uri: rows[uri]["ns"] for uri in rows}
    result["forward_fraction"] = {uri: forward_fraction(uri) for uri in rows}
    result["table"] = table
    result["step_cpu_ms"] = cpu_step
    result["residual_ms"] = cpu_step - total
    result["residual_share"] = (cpu_step - total) / cpu_step
    result["round_mean_ms"] = round_mean
    result["row_sum_ms"] = sum(r["ns"] for r in rows.values()) / 1e6
    result["rows_over_round"] = result["row_sum_ms"] / round_mean
    result["forward_round_ms"] = forward_round
    result["forward_backward_round_ms"] = both_round
    result["tiny"] = {"round_mean_ms": tiny_round, "row_sum_ms": sum(r["ns"] for r in tiny_rows.values()) / 1e6,
                      "step_cpu_ms": None}
    # The reference host, as the probe's own `machine` line prints it in the same file.
    result["machine"] = {"host": os.uname().nodename, "hardware_threads": os.cpu_count(),
                         "cpu": "AMD EPYC 7343 16-Core", "isa": "AVX2 (no AVX-512)"}
    result["load_average"]["after"] = load_average()
    if with_torch:
        result["like_for_like"] = elementwise_side_by_side()

    if projections is not None:
        matmul_profile = sum(rows[uri]["ns"] for uri in MATMUL_URIS if uri in rows)
        result["matmul_profile_row_ms"] = ms(matmul_profile)
        result["matmul_vs_profile_pct"] = 100.0 * (result["matmul_measured_ms"] -
                                                   ms(matmul_profile)) / ms(matmul_profile)
    return result


def print_table(result: dict) -> None:
    print(f"one d=256 step: CPU {result['step_cpu_ms']:.2f} ms "
          f"(wall median {result['step_wall_median_ms']:.1f} ms, load "
          f"{result['load_average']['before']:.0f} -> {result['load_average']['after']:.0f})")
    print(f"{'row':66s} {'ms':>8s} {'share':>7s}")
    for row in result["table"]:
        print(f"{row['row']:66s} {row['ms']:8.2f} {100 * row['share']:6.1f}%")
    print(f"{'residual':66s} {result['residual_ms']:8.2f} "
          f"{100 * result['residual_share']:6.1f}%")
    print(f"{'total':66s} {result['step_cpu_ms']:8.2f}")
    print(f"rows sum {result['row_sum_ms']:.1f} ms against a {result['round_mean_ms']:.1f} ms "
          f"round mean ({100 * result['rows_over_round']:.1f}%)")
    if "matmul_vs_profile_pct" in result:
        print(f"matmul: {result['matmul_measured_ms']:.2f} ms by shape against "
              f"{result['matmul_profile_row_ms']:.2f} ms in the profile's three rows "
              f"({result['matmul_vs_profile_pct']:+.1f}%)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("count", "budget", "measure"))
    parser.add_argument("--json", default=None)
    parser.add_argument("--steps", type=int, default=32)
    parser.add_argument("--warmup", type=int, default=3)
    parser.add_argument("--torch", action="store_true",
                        help="also measure the element-wise like-for-like against torch")
    args = parser.parse_args()
    if args.mode == "count":
        return counts_mode()
    result = budget(args.mode == "measure", args.torch, args.steps, args.warmup)
    result["generated_at"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    result["mode"] = args.mode
    print_table(result)
    if args.json:
        Path(args.json).write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
        print(f"result file: {args.json}")
    failures = []
    if any(row["ms"] <= 0 for row in result["table"]):
        failures.append("a row measured no time")
    if not 0.85 <= result["rows_over_round"] <= 1.15:
        failures.append(f"the rows sum to {100 * result['rows_over_round']:.1f}% of the round "
                        "mean")
    if abs(result["residual_share"]) > 0.15:
        failures.append(f"the residual is {100 * result['residual_share']:.1f}% of the step")
    for message in failures:
        print(f"FAIL: {message}")
    if failures:
        return 1
    print("step budget: PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())