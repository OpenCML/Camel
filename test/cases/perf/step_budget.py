def camel_exe() -> str:
    # The install this case measures: `--camel <path>` names it (the author's ruling of 2026-10-25
    # replaced the `CAMEL_EXE` environment switch -- and with it this function's `CAMEL_TIER` switch,
    # which nothing in the tree ever set -- with that argument); without it, `$CAMEL_HOME/bin/camel`,
    # else this tree's `out/latest/bin/camel`. One rule, in one place: test/tools/camel_arg.py.
    return CAMEL


def environment() -> dict:
    env = dict(os.environ)
    env.setdefault("CAMEL_HOME", str(Path(CAMEL).resolve().parents[1]))
    return env


def run(program: Path, passes: list[str], args: list[str] | None = None,
        cpu_time: bool = False) -> dict:
    command = [camel_exe(), "-t", "1", "--block-limit", "8192", str(program), *passes]
    command += args if args is not None else ["--arg", "bench=false", "--arg", "init_dir=",
                                              "--arg", "final_dir="]
    if cpu_time:
        command = ["/usr/bin/time", "-f", "cpu %U %S"] + command
    started = time.perf_counter()
    proc = subprocess.run(command, env=environment(), capture_output=True, text=True)
    wall = time.perf_counter() - started
    cpu = None
    match = re.search(r"^cpu ([0-9.]+) ([0-9.]+)$", proc.stderr, re.MULTILINE)
    if match:
        cpu = float(match.group(1)) + float(match.group(2))
    if proc.returncode != 0:
        raise SystemExit(f"camel failed ({proc.returncode}):\n{proc.stdout[-2000:]}\n"
                         f"{proc.stderr[-2000:]}")
    return {"command": command, "cpu": cpu, "wall": wall, "stdout": proc.stdout,
            "stderr": proc.stderr}


def bench_ms(stdout: str) -> list[float]:
    return [float(m.group(1)) for m in re.finditer(r"naive bench step=\d+ ms=([0-9.]+)", stdout)]


def median(values: list[float]):
    return sorted(values)[len(values) // 2] if values else None


def profile(program: Path, backend: str = "std::jit") -> dict:
    """Run the program under `std::profile`; the session must be armed before the scheduler."""
    with tempfile.TemporaryDirectory() as t:
        report = Path(t) / "profile.json"
        result = run(program, ["tensor::fuse", "std::profile", "report=true",
                               f'json="{report.as_posix()}"', "top=0", backend],
                     ["--arg", "bench=true", "--arg", "init_dir=", "--arg", "final_dir="])
        if not report.exists():
            raise SystemExit(f"std::profile wrote no JSON report:\n{result['stdout'][-2000:]}")
        doc = json.loads(report.read_text(encoding="utf-8"))
        doc["_bench"] = bench_ms(result["stdout"])
        doc["_stdout"] = result["stdout"]
        return doc


def config_line(stdout: str) -> dict:
    match = re.search(r"naive config batch=(\d+) sequence=(\d+) d_model=(\d+) heads=(\d+) "
                      r"d_ff=(\d+) vocab=(\d+) blocks=(\d+) params=(\d+)", stdout)
    if not match:
        raise SystemExit("the program printed no config line")
    keys = ("batch", "sequence", "d_model", "heads", "d_ff", "vocab", "blocks", "params")
    return {key: int(match.group(i + 1)) for i, key in enumerate(keys)}


def load_average() -> float:
    try:
        return float(Path("/proc/loadavg").read_text().split()[0])
    except OSError:
        return float("nan")


def per_step(doc: dict) -> dict[str, dict]:
    """Operator ns per round, for the operators that run every round.

    A row whose calls are not a multiple of the round count ran partly or wholly outside the loop
    (the weights' `randn`, the optimizer's state, `with_grad`); those are start-up, not the step.
    """
    rounds = doc["step"]["rounds"]
    out = {}
    for row in doc["operator_rows"]:
        if row["calls"] and row["calls"] % rounds == 0:
            out[row["uri"]] = {"ns": row["ns"] / rounds, "calls": row["calls"] / rounds}
    return out


def row_alloc_per_step(doc: dict) -> dict[str, float]:
    rounds = doc["step"]["rounds"]
    return {row["uri"]: row["alloc_ns"] / rounds for row in doc["operator_rows"]}


