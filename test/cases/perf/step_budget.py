# ---------------------------------------------------------------------------
# Generating the step


def generate(cell: dict, steps: int, warmup: int = 3, phase: str = "full",
             prints: bool = True) -> str:
    """train_step.cml at this cell, with the phase's timed body and optionally its prints."""
    text = TRAIN_STEP.read_text(encoding="utf-8")
    for old, new, count in SUBSTITUTIONS:
        got = text.count(old)
        if got != count:
            raise SystemExit(f"train_step.cml changed shape: {old!r} occurs {got} times, "
                             f"expected {count}")
        text = text.replace(old, new.format(steps=steps, **cell))
    # The initial and final loss are printed once each, outside the step.  Removing them keeps the
    # profile's rows to the loop's own calls, so a row divided by the round count is a per-step
    # number rather than a per-step plus two evaluations.
    for name in ("before", "after"):
        old = f"    let {name} = loss<{'model' if name == 'before' else 'trained'}>(x, labels)"
        if text.count(old) != 1:
            raise SystemExit(f"train_step.cml changed shape: {old!r} not found once")
        text = text.replace(old, f"    let {name} = 0.0")
    if not prints:
        for line in ('            if bench && i >= warmup then {\n'
                     '                `naive bench step=${i} ms=${elapsed * 1000.0:.6f}`->println\n'
                     '            }\n',
                     '            `naive step=${i} loss=${value:.9f}`->println\n'):
            if text.count(line) != 1:
                raise SystemExit(f"train_step.cml changed shape: {line!r} not found once")
            text = text.replace(line, "")
    if phase == "forward":
        # No gradient and no update: the same forward graph, called once per round.
        old = ("            let (value, gradient) = loss_grad<m>(x, labels)\n"
               "            let next = adam(m, gradient, st, lr)")
        if text.count(old) != 1:
            raise SystemExit("train_step.cml changed: the timed body is not the expected one")
        text = text.replace(old, "            let value = loss<m>(x, labels)\n"
                                 "            let next = (m, st)")
    elif phase == "forward-backward":
        old = "            let next = adam(m, gradient, st, lr)"
        if text.count(old) != 1:
            raise SystemExit("train_step.cml changed: the update is not the expected one")
        text = text.replace(old, "            let next = (m, st)")
    return text


def expected_products(cell: dict) -> dict:
    """The products one round issues, derived from the program's own shapes.

    For C = A @ B with A[m, k] and B[k, n], the gradient along the left argument is
    dC[m, n] @ B^T[n, k] (m x k x n, B transposed) and along the right one is
    A^T[k, m] @ dC[m, n] (k x n x m, A transposed).
    """
    tokens, d = cell["batch"] * cell["sequence"], cell["d_model"]
    d_ff, vocab, blocks = cell["d_ff"], cell["vocab"], cell["blocks"]

    def left(m, k, n):
        return f"{m}x{k}x{n}tB"

    def right(m, k, n):
        return f"{k}x{n}x{m}tA"

    forward = {
        f"{tokens}x{d}x{d}": 4 * blocks,          # q, k, v, wo
        f"{tokens}x{d_ff}x{d}": blocks,           # w1
        f"{tokens}x{d}x{d_ff}": blocks,           # w2
        f"{tokens}x{vocab}x{d}": 1,               # the vocabulary projection
    }
    out = dict(forward)
    for m, k, n in ((tokens, d, d), (tokens, d, d_ff), (tokens, d_ff, d), (tokens, d, vocab)):
        count = forward[f"{m}x{n}x{k}"]
        out[left(m, k, n)] = count
        out[right(m, k, n)] = count
    return out


